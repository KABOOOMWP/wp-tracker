package wppadel

import kotlinx.kover.gradle.plugin.dsl.KoverProjectExtension
import org.gradle.api.Project
import org.gradle.kotlin.dsl.configure

/** Kover line and branch coverage of the unit tests; each module sets its floor in its build script. */
internal fun Project.configureCoverage() {
    pluginManager.apply("org.jetbrains.kotlinx.kover")
    extensions.configure<KoverProjectExtension> {
        reports.filters.excludes {
            // Compose UI: the instrumented tests (connectedDebugAndroidTest) cover it, not the JVM unit tests
            annotatedBy("androidx.compose.runtime.Composable")
            // Generated by the Compose compiler: the lambdas of composables that capture nothing
            classes("*.ComposableSingletons$*")
        }
    }
}
