package wppadel

import kotlinx.kover.gradle.plugin.dsl.KoverProjectExtension
import org.gradle.api.Project
import org.gradle.kotlin.dsl.configure

/** Kover line and branch coverage of the unit tests; each module sets its floor in its build script. */
internal fun Project.configureCoverage() {
    pluginManager.apply("org.jetbrains.kotlinx.kover")
    extensions.configure<KoverProjectExtension> {
        reports.filters.excludes {
            // Compose UI: the instrumented tests (connectedDebugAndroidTest) cover it, not the JVM unit tests
            annotatedBy("androidx.compose.runtime.Composable")
            // Generated by the Compose compiler: the lambdas of composables that capture nothing
            classes("*.ComposableSingletons$*")
            // The Compose files' top-level icons, colours and preview helpers, and the lambdas inside composables
            classes(*COMPOSE_FILE_CLASSES)
            // Needs a device: the activities, the Data Layer link (androidTest covers it) and the vibrator factory
            classes("*.MainActivity*", "*.DataLayerChannel*", "*.Haptics\$Companion")
        }
    }
}

/** The file classes of the Compose UI files (`<File>Kt` and their `<File>Kt$…` lambdas), by module. */
private val COMPOSE_FILE_CLASSES = arrayOf(
    "*.board.*Kt*", // android/common: MatchBoard, SummaryParts, StrokeIcon, Theme
    "*.presentation.WatchAppKt*", // android/watch
    "*.presentation.*.*Kt*",
    "*.phone.BoardAppKt*", // android/phone
    "*.phone.NameEditorKt*",
)
